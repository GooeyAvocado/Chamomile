CREATE TABLE chamomile.images (
	image_id int4 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	image_prompt_tx text NULL,
	image_neg_prompt_tx text NULL,
	image_step_cnt int4 NULL,
	image_sampler_tx text NULL,
	image_schedule_tp text NULL,
	image_cfg_scl_num float8 NULL,
	image_seed_num int8 NULL,
	image_hght_num int4 NULL,
	image_wdth_num int4 NULL,
	image_fav_in bool DEFAULT false NULL,
	image_bytes_tx bytea NOT NULL,
	model_title_tx text NULL,
	cre_ts timestamp(4) DEFAULT now() NULL,
	image_hires_bytes_tx bytea NULL,
	image_hires_in bool GENERATED ALWAYS AS (image_hires_bytes_tx IS NOT NULL AND length(image_hires_bytes_tx) > 0) STORED NULL,
	image_base_prompt_tx text NULL,

	-- I don't think anyone prompts in other languages but if so change the tsvector
	image_base_prompt_fts tsvector GENERATED ALWAYS AS (to_tsvector('english'::regconfig, image_base_prompt_tx)) STORED NULL,
	image_prompt_fts tsvector GENERATED ALWAYS AS (to_tsvector('english'::regconfig, image_prompt_tx)) STORED NULL,

	CONSTRAINT pk_image PRIMARY KEY (image_id),
	CONSTRAINT images_models_fk FOREIGN KEY (model_title_tx) REFERENCES chamomile.models(model_title_tx)
);

CREATE TABLE chamomile.models (
	model_title_tx text not null,
	model_nm text not null,
	model_desc_tx text not null,
	model_avail_in boolean not null,
	model_type_tx varchar null, 
	model_type_cd varchar null,
	image_id int4 null,
	CONSTRAINT pk_model PRIMARY KEY (model_title_tx),
	CONSTRAINT fk_model_image FOREIGN KEY (image_id) REFERENCES chamomile.images(image_id)
);


CREATE TABLE chamomile.lora (
	lora_alias_tx         text,
	lora_nm               text,
	lora_desc_tx          text,
	lora_sample_prompt_tx text,
	lora_avail_in        boolean not null,
	lora_type_cd          varchar,
	image_id int4 null,
	CONSTRAINT pk_lora PRIMARY KEY (lora_alias_tx),
	CONSTRAINT fk_lora_image FOREIGN KEY (image_id) REFERENCES chamomile.images(image_id)
);


CREATE TABLE chamomile.prompts (
	prompt_id             int4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	prompt_nm             text,
	prompt_prompt_tx      text,
	prompt_neg_prompt_tx  text,
	prompt_step_cnt       int4,
	prompt_sampler_tx     text,
	prompt_schedule_tp    text,
	prompt_cfg_scl_num    int4,
	prompt_hght_num       int4,
	prompt_wdth_num       int4,
	image_id int4 null,
	CONSTRAINT pk_prompt PRIMARY KEY (prompt_id),
	CONSTRAINT fk_prompt_image FOREIGN KEY (image_id) REFERENCES chamomile.images(image_id)
);

ALTER TABLE chamomile.images ADD model_title_tx text NULL;
ALTER TABLE chamomile.images ADD CONSTRAINT images_models_fk FOREIGN KEY (model_title_tx) REFERENCES chamomile.models(model_title_tx);

CREATE TABLE chamomile.images_lora_map (
	image_id int4 NULL,
	lora_alias_tx text NULL,
	CONSTRAINT images_lora_map_images_fk FOREIGN KEY (image_id) REFERENCES chamomile.images(image_id),
	CONSTRAINT images_lora_map_lora_fk FOREIGN KEY (lora_alias_tx) REFERENCES chamomile.lora(lora_alias_tx)
);


CREATE INDEX idx_image_base_prompt_fts
  ON chamomile.images USING GIN (image_base_prompt_fts);

CREATE INDEX idx_image_prompt_fts
  ON chamomile.images USING GIN (image_prompt_fts);